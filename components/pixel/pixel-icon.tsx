  envelope: ['########', '##....##', '#.#..#.#', '#..##..#', '#......#', '#......#', '########', '........'],
  star: ['...##...', '...##...', '########', '.######.', '..####..', '.##..##.', '##....##', '........'],
  heart: ['.##..##.', '########', '########', '########', '.######.', '..####..', '...##...', '........'],
  terminal: ['########', '#......#', '#.#....#', '#..#...#', '#.#.##.#', '#......#', '########', '..####..'],
  chart: ['........', '......#.', '......#.', '...#..#.', '...#..#.', '#..#..#.', '#..#..#.', '########'],
  tv: ['.#...#..', '..#.#...', '########', '#......#', '#.+..+.#', '#......#', '########', '.#....#.'],
  monitor: ['########', '#++++++#', '#++++++#', '#++++++#', '########', '...##...', '..####..', '........'],
