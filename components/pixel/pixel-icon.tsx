export function PixelIcon({
  name,
  className,
  accent = '#fff6e0',
}: {
  name: PixelIconName
  className?: string
  accent?: string
}) {
  const rows = ICONS[name]
  return (
    <svg
      viewBox="0 0 8 8"
      aria-hidden="true"
      shapeRendering="crispEdges"
      className={cn('size-4 shrink-0', className)}
      fill="currentColor"
    >
      {rows.flatMap((row, y) =>
        row.split('').map((ch, x) =>
          ch === '.' ? null : (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === '+' ? accent : undefined} />
          ),
        ),
      )}
    </svg>
  )
}
